import { test, expect } from "@playwright/test";
import { resolve } from "node:path";
import { mkdirSync, writeFileSync } from "node:fs";

// Start scripts/serve_literature_workbench.py first. No browser route fixtures in this test.
test("real local PDF to READY to chat evidence, selection restore and revocation", async ({ page }) => {
  test.skip(process.env.BIOAGENT_REAL_KNOWLEDGE_UI !== "1", "Requires the explicit local Mock acceptance server and prepared model bundles.");
  test.setTimeout(240_000);
  const root = "http://127.0.0.1:4180";
  const baseName = `UI 文献 ${Date.now()}`;
  const results: Record<string, unknown> = { baseName, started: new Date().toISOString(), events: [] };
  const observed: string[] = [];
  await page.goto(root);
  await page.getByLabel("新项目名称").fill(baseName); await page.getByRole("button", { name: "创建项目", exact: true }).click();
  await page.getByLabel("新对话名称").fill("文献对话"); await page.getByRole("button", { name: "创建对话", exact: true }).click();
  await expect(page.locator(".conversation > header")).toContainText("文献对话");
  await page.getByRole("button", { name: "设置", exact: true }).click();
  await page.getByLabel("名称", { exact: true }).fill("本地验收 Mock"); await page.getByLabel("接口协议").selectOption("ollama");
  await page.getByLabel("模型", { exact: true }).fill("mock-task40"); await page.getByLabel("API Base URL").fill("http://127.0.0.1:11434");
  await page.getByRole("button", { name: "保存模型", exact: true }).click();
  await expect(page.getByLabel("已保存模型")).not.toHaveValue("");
  await page.getByRole("button", { name: "返回聊天", exact: true }).click();
  await page.getByLabel("本轮模型").selectOption({ label: "本地验收 Mock" });
  await page.getByRole("button", { name: "知识库", exact: true }).click();
  await page.getByLabel("新知识库名称").fill(baseName); await page.getByRole("button", { name: "创建知识库", exact: true }).click();
  await expect(page.getByLabel("管理知识库")).not.toHaveValue("");
  await expect(page.getByLabel("本地 PDF")).toBeEnabled({ timeout: 30_000 });
  await page.getByLabel("本地 PDF").setInputFiles([resolve("../data/task38/samples/digital_twocolumn_figure_table.pdf"), resolve("../data/task38/samples/scan_ocr.pdf"), resolve("../data/task38/samples/cross_page_table.pdf")]);
  await page.getByRole("button", { name: "上传并解析", exact: true }).click();
  const docs = page.locator(".knowledge-document");
  await expect(docs).toHaveCount(3);
  await expect(page.getByRole("button", { name: "建立索引", exact: true })).toHaveCount(3, { timeout: 120_000 });
  for (const doc of await docs.all()) await doc.getByRole("button", { name: "建立索引", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "可检索 · READY" })).toHaveCount(3, { timeout: 60_000 });
  results.ready = new Date().toISOString();
  await page.getByRole("button", { name: "返回聊天", exact: true }).click();
  await page.getByLabel(`知识库 ${baseName}`, { exact: true }).check();
  await expect(page.getByLabel(`知识库 ${baseName}`, { exact: true })).toBeChecked();
  await page.getByLabel("消息", { exact: true }).fill("文献 Results table mass mg Figure Control treated 图表说明什么？");
  await page.getByRole("button", { name: "发送", exact: true }).click();
  await expect(page.getByLabel("文献回答")).toContainText("引用验证完成", { timeout: 30_000 });
  await expect(page.getByLabel("文献回答")).toContainText("Mock 本地文献回答");
  await expect(page.getByLabel("文献回答")).toContainText("条命中");
  const pdf = page.getByRole("button", { name: /打开 PDF 第/ }).first(); await pdf.click();
  const frame = page.getByAltText(/^PDF 第/); await expect(frame).toBeVisible();
  await expect.poll(() => frame.evaluate((node: HTMLImageElement) => node.complete && node.naturalWidth > 500)).toBeTruthy();
  const pdfUrl = await page.getByRole("link", { name: "下载原始 PDF" }).getAttribute("href"); expect(pdfUrl).toContain("/pdf");
  const pdfResponse = await page.request.get(root + pdfUrl!.split("#")[0]); expect(pdfResponse.ok()).toBeTruthy(); expect(pdfResponse.headers()["content-type"]).toContain("application/pdf");
  const dir = resolve("../data/task40/ui-acceptance"); mkdirSync(dir, { recursive: true });
  await page.screenshot({ path: resolve(dir, "pdf-page.png") });
  const eventsUrl = root + pdfUrl!.replace(/\/evidence\/.*$/, "/knowledge/events?after=0");
  const eventText = await (await page.request.get(eventsUrl)).text(); observed.push(eventText);
  for (const stage of ["RETRIEVING", "GENERATING", "VALIDATING", "answer.delta", "completed"]) expect(eventText).toContain(stage);
  await page.getByRole("button", { name: "关闭预览", exact: true }).click();
  await page.getByRole("button", { name: "查看表格结构", exact: true }).first().click(); await expect(page.locator(".evidence-preview table")).toBeVisible();
  await expect(page.locator(".evidence-preview table")).toContainText("Mass");
  await page.getByRole("button", { name: "关闭预览", exact: true }).click();
  await page.getByLabel("消息", { exact: true }).fill("文献图1的柱高是否表示实验结果还是仅用于展示排版");
  await page.getByRole("button", { name: "发送", exact: true }).click();
  await expect(page.getByLabel("文献回答").last()).toContainText("引用验证完成", { timeout: 30_000 });
  const picture = page.getByLabel("文献回答").last().locator(".evidence").filter({ hasText: "仅依据图注 / OCR" }).first();
  await expect(picture).toBeVisible(); await picture.getByRole("button", { name: "查看裁剪图片", exact: true }).click();
  const image = page.getByAltText("论文图表裁剪"); await expect(image).toBeVisible();
  await expect.poll(() => image.evaluate((node: HTMLImageElement) => node.complete && node.naturalWidth > 0)).toBeTruthy();
  await page.screenshot({ path: resolve(dir, "picture.png") });
  await page.getByRole("button", { name: "关闭预览", exact: true }).click();
  await page.getByLabel("新对话名称").fill("另一对话"); await page.getByRole("button", { name: "创建对话", exact: true }).click();
  await expect(page.getByLabel(`知识库 ${baseName}`, { exact: true })).not.toBeChecked();
  await page.getByRole("button", { name: "文献对话", exact: true }).click(); await expect(page.getByLabel(`知识库 ${baseName}`, { exact: true })).toBeChecked();
  await page.reload(); await expect(page.getByLabel(`知识库 ${baseName}`, { exact: true })).toBeChecked(); await expect(page.getByLabel("文献回答").first()).toContainText("Mock 本地文献回答");
  await page.screenshot({ path: resolve(dir, "answer.png"), fullPage: true });
  await page.getByRole("button", { name: "知识库", exact: true }).click();
  await page.getByLabel("管理知识库").selectOption({ label: baseName });
  await docs.filter({ hasText: "digital_twocolumn_figure_table.pdf" }).getByRole("button", { name: "重建索引", exact: true }).click();
  await page.getByRole("button", { name: "返回聊天", exact: true }).click();
  await expect(page.getByLabel("文献回答").filter({ hasText: "证据已失效" })).toHaveCount(2, { timeout: 15_000 });
  await expect(page.locator(".knowledge-answer-text")).toHaveCount(0);
  await page.getByLabel("消息", { exact: true }).fill("文献 Results table mass mg Figure Control treated 图表说明什么？"); await page.getByRole("button", { name: "发送", exact: true }).click();
  await expect(page.getByLabel("文献回答").last()).toContainText("引用验证完成", { timeout: 30_000 });
  await page.getByRole("button", { name: "知识库", exact: true }).click(); await page.getByLabel("管理知识库").selectOption({ label: baseName });
  await expect(docs).toHaveCount(3);
  for (let remaining = 3; remaining > 0; remaining--) { await docs.first().getByRole("button", { name: "删除文献", exact: true }).click(); await expect(docs).toHaveCount(remaining - 1); }
  await page.getByRole("button", { name: "返回聊天", exact: true }).click(); await expect(page.getByLabel("文献回答").filter({ hasText: "证据已失效" })).toHaveCount(3, { timeout: 15_000 });
  expect(await (await page.request.get(eventsUrl)).text()).not.toContain("answer.delta");
  expect((await page.request.get(root + pdfUrl!.split("#")[0])).status()).toBe(409);
  await page.setViewportSize({ width: 390, height: 844 }); await expect(page.getByRole("textbox", { name: "消息" })).toBeVisible();
  await page.screenshot({ path: resolve(dir, "revoked-mobile.png"), fullPage: true });
  results.finished = new Date().toISOString(); results.events = observed; results.pdfStatusAfterDelete = 409; results.completed = true;
  writeFileSync(resolve(dir, "acceptance.json"), JSON.stringify(results, null, 2));
});
