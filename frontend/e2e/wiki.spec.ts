import { test, expect } from "@playwright/test";
import { resolve } from "node:path";
import { mkdirSync, writeFileSync } from "node:fs";

test("real local Wiki preflight build links evidence cancel and revocation", async ({ page }) => {
  test.skip(process.env.BIOAGENT_REAL_WIKI_UI !== "1", "Requires explicit isolated local Mock server on 4183, prepared Docling/E5 and self-authored PDFs.");
  test.setTimeout(240_000);
  const root = "http://127.0.0.1:4183"; const name = `Wiki UI ${Date.now()}`;
  const output = resolve("../data/task43/ui-acceptance"); mkdirSync(output, { recursive: true });
  let builds = 0; page.on("request", (req) => { if (req.url().endsWith("/wiki/build")) builds++; });
  await page.goto(root);
  await page.getByRole("button", { name: "设置", exact: true }).click();
  await page.getByLabel("名称", { exact: true }).fill(name); await page.getByLabel("接口协议").selectOption("ollama");
  await page.getByLabel("模型", { exact: true }).fill("mock-wiki-ui-slow"); await page.getByLabel("API Base URL").fill("http://127.0.0.1:11434");
  await page.getByRole("button", { name: "保存模型", exact: true }).click();
  await expect(page.getByLabel("已保存模型")).not.toHaveValue("");
  await page.getByRole("button", { name: "返回聊天", exact: true }).click();
  await page.getByRole("button", { name: "知识库", exact: true }).click();
  await page.getByLabel("新知识库名称").fill(name); await page.getByRole("button", { name: "创建知识库", exact: true }).click();
  await expect(page.getByLabel("本地 PDF")).toBeEnabled({ timeout: 30_000 });
  await page.getByLabel("本地 PDF").setInputFiles(resolve("../data/task38/samples/scan_ocr.pdf"));
  await page.getByRole("button", { name: "上传并解析", exact: true }).click();
  await page.getByRole("button", { name: "建立索引", exact: true }).click({ timeout: 120_000 });
  await expect(page.getByRole("status").filter({ hasText: "可检索 · READY" })).toHaveCount(1, { timeout: 60_000 });
  expect(builds).toBe(0);
  await page.getByRole("button", { name: "管理文献 Wiki", exact: true }).click();
  await page.getByLabel("Wiki 构建模型").selectOption({ label: `${name} · mock-wiki-ui-slow` });
  await page.getByRole("button", { name: "预检 Wiki 构建", exact: true }).click();
  await expect(page.getByLabel("Wiki 构建预检")).toContainText("协议限额未经实测");
  expect(builds).toBe(0);
  await page.getByRole("button", { name: "确认开始 Wiki 构建", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Wiki：COMPLETED" })).toBeVisible({ timeout: 30_000 });
  const nav = page.getByRole("navigation", { name: "Wiki 页面导航" });
  await expect(nav.getByRole("button")).toHaveCount(3);
  await nav.getByRole("button", { name: /主题综合/ }).click();
  await expect(page.getByRole("article", { name: "Wiki 页面" })).toContainText("候选分歧");
  await page.getByRole("navigation", { name: "Wiki 相关页面" }).getByRole("button").click();
  await expect(page.getByRole("article", { name: "Wiki 页面" })).toContainText("此页输入文献");
  await page.getByRole("button", { name: /原文证据 · PDF 第/ }).first().click();
  const image = page.getByAltText(/^Wiki 原文 PDF 第/);
  await expect(image).toBeVisible();
  await expect.poll(() => image.evaluate((node: HTMLImageElement) => node.complete && node.naturalWidth > 500)).toBeTruthy();
  await page.screenshot({ path: resolve(output, "source.png") });
  await page.getByRole("button", { name: "关闭预览", exact: true }).click();
  const exportUrl = await page.getByRole("link", { name: "导出此页 Markdown" }).getAttribute("href");
  const exported = await page.request.get(root + exportUrl!); expect(exported.ok()).toBeTruthy(); expect(await exported.text()).toContain("AI generated");
  for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 800 });
    const layout = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, overflow: Array.from(document.querySelectorAll("body *")).filter((el) => el.getBoundingClientRect().right > innerWidth + 1).map((el) => ({ tag: el.tagName, class: el.className, width: el.getBoundingClientRect().width, text: el.textContent?.slice(0, 80) })) }));
    writeFileSync(resolve(output, `layout-${width}.json`), JSON.stringify(layout, null, 2));
    await page.screenshot({ path: resolve(output, `page-${width}.png`), fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
    if (width >= 1200) expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight + 1)).toBeTruthy();
    await page.getByRole("link", { name: "导出此页 Markdown" }).scrollIntoViewIfNeeded();
    await expect(page.getByRole("link", { name: "导出此页 Markdown" })).toBeInViewport();
  }
  await page.setViewportSize({ width: 1280, height: 800 });
  // Rebuild immediately withdraws paper AND aggregate navigation.
  await page.getByRole("button", { name: "重建索引", exact: true }).click();
  await expect(nav.getByRole("button").filter({ hasText: "来源已失效" })).toHaveCount(3, { timeout: 10_000 });
  await expect(page.getByRole("article", { name: "Wiki 页面" })).toHaveCount(0);
  await expect(page.getByRole("status").filter({ hasText: "可检索 · READY" })).toHaveCount(1, { timeout: 60_000 });
  await page.getByRole("button", { name: "预检 Wiki 构建", exact: true }).click();
  await page.getByRole("button", { name: "确认开始 Wiki 构建", exact: true }).click();
  await page.getByRole("button", { name: "停止 Wiki 构建", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Wiki：CANCELLED" })).toBeVisible();
  await page.screenshot({ path: resolve(output, "cancelled.png") });
  writeFileSync(resolve(output, "result.json"), JSON.stringify({ models: "Mock only", local: "real Docling/E5/Qdrant", builds, sourcePreview: true, links: true, cancel: true, recursiveRevocation: true, documentScrollRegression: false }, null, 2));
});
